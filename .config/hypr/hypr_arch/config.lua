hl.config({
	-- Настройки указателя мыши и курсора
	cursor = {
		-- Отключение аппаратного курсора
		no_hardware_cursors = 1,
	},

	-- Главные параметры окон, сетки и границ
	general = {
		gaps_in = 2, -- Расстояние между окнами
		gaps_out = 3, -- Расстояние между окнами и краями экрана
		border_size = 2, -- Толщина рамки вокруг окон

		-- Цвет границ окон
		col = {
			-- Градиент для активного (выделенного) окна из двух цветов под углом 45 градусов
			active_border = { colors = { "rgba(f2cdcdee)", "rgba(f5e0dcee)" }, angle = 45 },
			-- Однотонный цвет границы для неактивных окон
			inactive_border = "rgba(1e1e2eff)",
		},

		resize_on_border = false, -- Изменение размера окон мышкой, потянув за самую крайнюю рамку
		allow_tearing = false, -- Разрешить разрыв кадра (Tearing) для полноэкранных игр (снижает инпут-лаг)
		layout = "dwindle", -- Используемый движок тайлинга по умолчанию (dwindle / master)
	},

	-- Декорации окон: скругление, прозрачность, размытие и тени
	decoration = {
		rounding = 8, -- Радиус скругления углов окон
		active_opacity = 1.0, -- Прозрачность активного окна (1.0 — полностью непрозрачно)
		inactive_opacity = 1.0, -- Прозрачность неактивных окон
		fullscreen_opacity = 1.0, -- Прозрачность окон в режиме "на весь экран"

		-- Настройки эффекта размытия (Blur) заднего фона за полупрозрачными окнами
		blur = {
			enabled = true, -- Включить размытие
			size = 8, -- Радиус размытия (сила эффекта)
			passes = 2, -- Количество проходов фильтра (чем больше, тем качественнее и тяжелее для GPU)
			ignore_opacity = true, -- Размывать фон, даже если само окно непрозрачное
			xray = true, -- Просвечивать сквозь другие окна до обоев (экономит ресурсы)
			vibrancy = 0.1696, -- Насыщенность цветов размытия
		},

		-- Настройки теней под окнами
		shadow = {
			enabled = true, -- Включить тени
			range = 4, -- Радиус рассеивания тени в пикселях
			render_power = 3, -- Насколько плавно падает тень (от 1 до 4)
			color = "rgba(1a1a1aee)", -- Цвет тени с альфа-каналом (прозрачностью)
			scale = 1.0, -- Масштаб тени относительно размера окна
		},
	},

	-- Специфичные параметры для тайлинг-движка Dwindle (похож на bspwm)
	dwindle = {
		preserve_split = true, -- Сохранять направление разделения окон (горизонтальное/вертикальное) при манипуляциях
	},

	-- Специфичные параметры для тайлинг-движка Master (одно главное окно, остальные в стек)
	master = {
		new_status = "master", -- Новые окна автоматически становятся главными (master)
	},

	-- Системные и смешанные настройки поведения WM
	misc = {
		disable_hyprland_logo = true, -- Отключить стандартные аниме-обои со слоганом Hyprland при запуске
		animate_manual_resizes = true, -- Анимировать изменение размеров окон при ручном перетаскивании границ
		animate_mouse_windowdragging = true, -- Анимировать перемещение окон при помощи зажатой мыши
		enable_swallow = true, -- Включить "поглощение": если запустить GUI-софт из терминала, терминал временно скроется
		disable_splash_rendering = true, -- Отключить приветственные splash-тексты на экране загрузки
		mouse_move_enables_dpms = true, -- Движение мыши выводит мониторы из спящего режима (DPMS)
	},

	-- Настройки устройств ввода: клавиатура, мышь и тачпад
	input = {
		kb_layout = "us,ru", -- Список языковых раскладок клавиатуры
		-- Горячие клавиши для смены раскладки: по Alt+Shift и по Win+Пробел
		kb_options = "grp:alt_shift_toggle,grp:win_space_toggle",

		scroll_method = "2fg", -- Метод прокрутки
		natural_scroll = true, -- Естественная прокрутка (движение пальца вверх двигает контент вверх)
		follow_mouse = 1, -- Фокус окна следует за указателем мыши
		sensitivity = 0, -- Чувствительность мыши (от -1.0 до 1.0, где 0 — стандартная системная)
		numlock_by_default = true, -- Автоматически включать клавишу NumLock при старте системы

		-- Отдельный блок настроек для сенсорных панелей ноутбуков
		touchpad = {
			natural_scroll = true, -- Естественная прокрутка для тачпада
		},
	},

	-- Глобальный переключатель анимаций системы
	animations = {
		enabled = true, -- Если выставить false, абсолютно все анимации выключатся
	},
})

-- Настройка параметров для конкретных физических устройств (по их ID/Имени)
hl.device({
	name = "BSK V3 PRO", -- Системное имя конкретной мыши
	sensitivity = -0.5, -- Индивидуальная чувствительность только для этого устройства
})
